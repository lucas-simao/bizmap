"""Go tests, fixtures, mocks and generated code are skipped by default, but
generated data-access code (sqlc) is kept and its queries are SQL (round 38)."""

from __future__ import annotations

from pathlib import Path

from bizmap.files import WalkOptions, go_generated_kind, iter_files
from bizmap.scan import scan_path

SQLC = '''// Code generated by sqlc. DO NOT EDIT.
// versions:
//   sqlc v1.25.0

package db

import "context"

const getOrder = `-- name: GetOrder :one
SELECT id, status FROM orders WHERE id = $1
`

func (q *Queries) GetOrder(ctx context.Context, id int) error {
	_, err := q.db.QueryContext(ctx, getOrder, id)
	return err
}

const setStatus = `-- name: SetStatus :exec
UPDATE orders SET status = $1 WHERE id = $2
`

func (q *Queries) SetStatus(ctx context.Context, status string, id int) error {
	_, err := q.db.ExecContext(ctx, setStatus, status, id)
	return err
}

type DBTX interface {
	ExecContext(context.Context, string, ...interface{}) (interface{}, error)
	QueryContext(context.Context, string, ...interface{}) (interface{}, error)
}

type Queries struct{ db DBTX }
'''

MOCKGEN = '''// Code generated by MockGen. DO NOT EDIT.
// Source: store.go

package store

type MockStore struct{}

func (m *MockStore) Save() error { return nil }
'''

PB = '''// Code generated by protoc-gen-go. DO NOT EDIT.
package pb

var raw = []byte{1, 2, 3}
'''

REAL = '''package store

import "database/sql"

func Save(db *sql.DB) error {
	_, err := db.Exec("UPDATE orders SET status = 'paid'")
	return err
}
'''

TEST = '''package store

import "testing"

func TestSave(t *testing.T) { _ = Save(nil) }
'''


def _w(root: Path, rel: str, body: str) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")


def _repo(root: Path) -> None:
    _w(root, "go.mod", "module example.com/shop\n\ngo 1.22\n")
    _w(root, "schema.sql", "CREATE TABLE orders (id int primary key, status text);\n")
    _w(root, "internal/store/store.go", REAL)
    _w(root, "internal/store/store_test.go", TEST)
    _w(root, "internal/store/store_mock.go", MOCKGEN)
    _w(root, "internal/store/mock_other.go", MOCKGEN)
    _w(root, "internal/store/gen_store.go", MOCKGEN)  # generated only by its header
    _w(root, "internal/store/mocks/store.go", MOCKGEN)
    _w(root, "internal/store/testdata/fixture.go", REAL)
    _w(root, "internal/pb/orders.pb.go", PB)
    _w(root, "internal/db/queries.sql.go", SQLC)


def test_kinds(tmp_path: Path) -> None:
    _repo(tmp_path)
    kind = lambda rel: go_generated_kind(tmp_path / rel)  # noqa: E731
    assert kind("internal/store/store.go") is None
    assert kind("internal/store/store_test.go") == "tests"
    assert kind("internal/store/store_mock.go") == "generated"
    assert kind("internal/store/gen_store.go") == "generated"
    assert kind("internal/pb/orders.pb.go") == "generated"
    assert kind("internal/db/queries.sql.go") is None  # sqlc: data access


def test_generated_code_that_runs_sql_is_kept(tmp_path: Path) -> None:
    body = "// Code generated by mytool. DO NOT EDIT.\n\npackage db\n\nfunc f(db DB) { db.ExecContext(ctx, q) }\n"
    _w(tmp_path, "x.go", body)
    assert go_generated_kind(tmp_path / "x.go") is None


def test_walk_skips_and_counts(tmp_path: Path) -> None:
    _repo(tmp_path)
    opts = WalkOptions()
    files = [p.relative_to(tmp_path.resolve()).as_posix() for p in iter_files(tmp_path, [".go"], options=opts)]
    assert files == ["internal/db/queries.sql.go", "internal/store/store.go"]
    assert opts.stats == {"generated_dirs": 1, "generated_files": 4, "go_test_dirs": 1, "go_tests": 1}
    everything = iter_files(tmp_path, [".go"], options=WalkOptions(skip_generated=False))
    assert len(everything) == 9
    back = iter_files(tmp_path, [".go"], options=WalkOptions(include=["*_test.go", "testdata"]))
    rels = {p.name for p in back}
    assert "store_test.go" in rels and "fixture.go" in rels


def test_mocks_and_testdata_dirs_only_for_go(tmp_path: Path) -> None:
    _w(tmp_path, "mocks/api.py", "def f():\n    pass\n")
    _w(tmp_path, "testdata/x.ts", "export const a = 1\n")
    assert len(iter_files(tmp_path, [".py"])) == 1
    assert len(iter_files(tmp_path, [".ts"])) == 1


def test_scan_finds_sqlc_queries_and_skips_the_rest(tmp_path: Path) -> None:
    _repo(tmp_path)
    graph = scan_path(tmp_path)
    data = {
        ((graph.nodes[e.from_id].attrs.get("evidence") or {}).get("file"), e.type, e.to_id)
        for e in graph.edges.values()
        if e.type in {"reads", "writes"}
    }
    files = {f for f, _t, _to in data}
    assert "internal/db/queries.sql.go" in files, data  # sqlc `-- name:` queries are SQL
    assert any(t == "writes" and f == "internal/db/queries.sql.go" for f, t, _ in data)
    assert any(t == "reads" and f == "internal/db/queries.sql.go" for f, t, _ in data)
    evidence_files = {(n.attrs.get("evidence") or {}).get("file") for n in graph.nodes.values()}
    assert not any(f and ("_test.go" in f or "mock" in f or ".pb.go" in f or "testdata" in f) for f in evidence_files)
    assert graph.attrs["skipped"]["go_tests"] == 1
