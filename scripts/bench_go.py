"""Synthetic Go repo benchmark: how the Go phase scales with the repo size.

    python scripts/bench_go.py 500 1000 2000 4000          # files (approx.)
    python scripts/bench_go.py --client 800                # one HTTP client with 800 methods
    python scripts/bench_go.py 2000 --profile              # cProfile top 25

Each domain has handler / service / repo packages, constants, SQL built with
const and fmt.Sprintf, cross-package calls, an interface, echo routes, calls to
the standard library, tests, a mockgen mock, a *.pb.go and an sqlc package.
Names are neutral (shop, orders, inventory…).
"""

from __future__ import annotations

import argparse
import cProfile
import io
import pstats
import sys
import tempfile
import time
from pathlib import Path

MOD = "example.com/shop"


def _w(root: Path, rel: str, body: str) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")


def domain(root: Path, d: int, extra: int) -> int:
    name = f"orders{d}"
    files = 0
    _w(root, f"internal/{name}/repo/consts.go", f'''package repo

const table = "{name}"
const selectCols = "id, status, total"
''')
    _w(root, f"internal/{name}/repo/repo.go", f'''package repo

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
)

type Repo struct {{ db *sql.DB }}

func New(db *sql.DB) *Repo {{ return &Repo{{db: db}} }}

func (r *Repo) Get(ctx context.Context, id int) error {{
	q := fmt.Sprintf("SELECT %s FROM %s WHERE id = $1", selectCols, table)
	if _, err := r.db.QueryContext(ctx, q, id); err != nil {{
		return fmt.Errorf("get: %w", err)
	}}
	return errors.New("x")
}}

func (r *Repo) SetStatus(ctx context.Context, id int, s string) error {{
	_, err := r.db.ExecContext(ctx, "UPDATE {name} SET status = $1 WHERE id = $2", s, id)
	return err
}}
''')
    _w(root, f"internal/{name}/service/service.go", f'''package service

import (
	"context"
	"fmt"
	"strings"

	"{MOD}/internal/{name}/repo"
)

type Store interface {{
	Get(ctx context.Context, id int) error
	SetStatus(ctx context.Context, id int, s string) error
}}

type Service struct {{ store Store }}

func New(r *repo.Repo) *Service {{ return &Service{{store: r}} }}

func (s *Service) Get(ctx context.Context, id int) error {{
	_ = strings.TrimSpace(fmt.Sprint(id))
	return s.store.Get(ctx, id)
}}

func (s *Service) Pay(ctx context.Context, id int) error {{
	return s.store.SetStatus(ctx, id, "paid")
}}
''')
    _w(root, f"internal/{name}/handler/handler.go", f'''package handler

import (
	"net/http"
	"strconv"

	"github.com/labstack/echo/v4"
	"{MOD}/internal/{name}/service"
)

type Handler struct {{ svc *service.Service }}

func Register(e *echo.Echo, svc *service.Service) {{
	h := &Handler{{svc: svc}}
	e.GET("/{name}/:id", h.Get)
	e.POST("/{name}/:id/pay", h.Pay)
}}

func (h *Handler) Get(c echo.Context) error {{
	id, _ := strconv.Atoi(c.Param("id"))
	return h.svc.Get(c.Request().Context(), id)
}}

func (h *Handler) Pay(c echo.Context) error {{
	id, _ := strconv.Atoi(c.Param("id"))
	if err := h.svc.Pay(c.Request().Context(), id); err != nil {{
		return c.JSON(http.StatusInternalServerError, err.Error())
	}}
	return c.NoContent(http.StatusOK)
}}
''')
    files += 4
    for i in range(extra):
        _w(root, f"internal/{name}/service/util{i}.go", f'''package service

import (
	"context"
	"fmt"
	"strings"
	"time"
)

func helper{i}(ctx context.Context, v string) string {{
	_ = ctx
	_ = time.Now()
	return strings.ToUpper(fmt.Sprintf("%s-%d", v, {i}))
}}

func (s *Service) Extra{i}(ctx context.Context, id int) error {{
	_ = helper{i}(ctx, "x")
	return s.store.Get(ctx, id)
}}
''')
        _w(root, f"internal/{name}/service/util{i}_test.go", f'''package service

import "testing"

func TestHelper{i}(t *testing.T) {{
	if helper{i}(nil, "a") == "" {{
		t.Fatal("empty")
	}}
}}
''')
        files += 2
    _w(root, f"internal/{name}/mocks/mock_store.go", '''// Code generated by MockGen. DO NOT EDIT.
package mocks

import (
	"context"
	"reflect"
)

type MockStore struct{ recorder *MockStoreRecorder }
type MockStoreRecorder struct{ mock *MockStore }

func (m *MockStore) Get(ctx context.Context, id int) error { _ = reflect.TypeOf(m); return nil }
func (m *MockStore) SetStatus(ctx context.Context, id int, s string) error { return nil }
func (mr *MockStoreRecorder) Get(ctx, id interface{}) { _ = reflect.TypeOf(mr) }
''')
    _w(root, f"internal/{name}/pb/{name}.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb\n\n"
       + "var file_desc = []byte{" + ", ".join(str(i % 256) for i in range(3000)) + "}\n")
    _w(root, f"internal/{name}/db/queries.sql.go", f'''// Code generated by sqlc. DO NOT EDIT.
package db

import "context"

const getOrder = `-- name: GetOrder :one
SELECT id, status FROM {name} WHERE id = $1
`

func (q *Queries) GetOrder(ctx context.Context, id int) error {{
	_, err := q.db.QueryContext(ctx, getOrder, id)
	return err
}}

type Queries struct{{ db DBTX }}
type DBTX interface{{ QueryContext(context.Context, string, ...interface{{}}) (interface{{}}, error) }}
''')
    return files + 3


def http_client(root: Path, methods: int) -> None:
    body = [
        "package client\n",
        'import (\n\t"context"\n\t"net/http"\n)\n',
        "type Client struct {\n\tbaseURL string\n\thttp *http.Client\n}\n",
        "func New(baseURL string) *Client { return &Client{baseURL: baseURL, http: http.DefaultClient} }\n",
        "func (c *Client) getJSON(ctx context.Context, path string) error {\n"
        "\treq, _ := http.NewRequestWithContext(ctx, http.MethodGet, c.baseURL+path, nil)\n"
        "\t_, err := c.http.Do(req)\n\treturn err\n}\n",
    ]
    for i in range(methods):
        body.append(
            f"func (c *Client) Item{i}(ctx context.Context) error {{ return c.getJSON(ctx, \"/items/{i}\") }}\n"
        )
    _w(root, "internal/client/client.go", "\n".join(body))


def heavy_util(root: Path, name: str, i: int) -> None:
    """A bigger file: 30 functions, each with stdlib calls and a branch."""
    funcs = []
    for k in range(30):
        funcs.append(f'''
func step{i}_{k}(ctx context.Context, in []string) (string, error) {{
	out := make([]string, 0, len(in))
	for _, v := range in {{
		if strings.HasPrefix(v, "x") {{
			out = append(out, strings.TrimSpace(fmt.Sprintf("%s-%d", v, {k})))
		}} else if len(v) > {k} {{
			out = append(out, strconv.Itoa(len(v)))
		}}
	}}
	if len(out) == 0 {{
		return "", errors.New("empty")
	}}
	_ = time.Now().Add(time.Duration({k}) * time.Second)
	b, err := json.Marshal(out)
	if err != nil {{
		return "", fmt.Errorf("marshal: %w", err)
	}}
	return string(b), ctx.Err()
}}
''')
    _w(root, f"internal/{name}/service/heavy{i}.go", "package service\n\nimport (\n\t\"context\"\n\t\"encoding/json\"\n"
       "\t\"errors\"\n\t\"fmt\"\n\t\"strconv\"\n\t\"strings\"\n\t\"time\"\n)\n" + "".join(funcs))


def build(root: Path, files: int, client: int = 0, heavy: bool = False) -> int:
    _w(root, "go.mod", f"module {MOD}\n\ngo 1.22\n")
    _w(root, "schema.sql", "".join(
        f"CREATE TABLE orders{d} (id int primary key, status text, total int);\n" for d in range(max(1, files // 25))
    ))
    made = 0
    d = 0
    while made < files:
        made += domain(root, d, extra=9)
        if heavy:
            for i in range(4):
                heavy_util(root, f"orders{d}", i)
            made += 4
        d += 1
    if client:
        http_client(root, client)
    return made


def run(n: int, client: int, profile: bool, heavy: bool = False, all_files: bool = False) -> None:
    from bizmap.scan import scan_path

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        made = build(root, n, client, heavy=heavy)
        if all_files:
            (root / "bizmap.yaml").write_text("scan:\n  skip_generated: false\n", encoding="utf-8")
        pr = cProfile.Profile() if profile else None
        t0 = time.perf_counter()
        if pr:
            pr.enable()
        graph = scan_path(root)
        if pr:
            pr.disable()
        dt = time.perf_counter() - t0
        edges = len(graph.edges)
        print(f"files={made} client_methods={client} nodes={len(graph.nodes)} edges={edges} scan={dt:.2f}s "
              f"({1000 * dt / max(made, 1):.1f} ms/file)", flush=True)
        if pr:
            out = io.StringIO()
            pstats.Stats(pr, stream=out).sort_stats("tottime").print_stats(25)
            print(out.getvalue())


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sizes", nargs="*", type=int)
    ap.add_argument("--client", type=int, default=0, help="also add one HTTP client with this many methods")
    ap.add_argument("--profile", action="store_true")
    ap.add_argument("--heavy", action="store_true", help="add bigger files with many standard-library calls")
    ap.add_argument("--all-files", action="store_true", help="also analyse tests, mocks and generated code")
    args = ap.parse_args(argv)
    sizes = args.sizes or ([0] if args.client else [500, 1000, 2000])
    for n in sizes:
        run(n, args.client, args.profile, heavy=args.heavy, all_files=args.all_files)
    return 0


if __name__ == "__main__":
    sys.exit(main())
